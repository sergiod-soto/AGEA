using UnityEngine;

using System;
using System.Collections.Generic;

/// <summary>
/// Gestiona la navegación entre pantallas.
/// 
/// Responsabilidades:
///   - Activar / desactivar Views
///   - Instanciar y destruir Presenters
///   - Ser el único punto desde el que se navega
/// 
/// Uso desde un Presenter:
///   Navigator.NavigateTo(ScreenManager.Screen.MenuPerfiles);
/// </summary>
public class ScreenManager : MonoBehaviour
{
    public static ScreenManager Instance { get; private set; }

    // ?? Asignar en el Inspector ??????????????????????????????????????????????
    [SerializeField] private MenuPrincipalView menuPrincipalView;
    [SerializeField] private MenuPerfilesView menuPerfilesView;
    [SerializeField] private PreferencesView preferencesView;
    [SerializeField] private IngameView ingameView;
    // ????????????????????????????????????????????????????????????????????????

    public enum Screen
    {
        MenuPrincipal,
        MenuPerfiles,
        Preferences,
        Ingame
    }

    private PresenterBase _currentPresenter;
    private List<MonoBehaviour> _allViews;

    // ?? Unity ????????????????????????????????????????????????????????????????

    private void Awake()
    {
        if (Instance != null && Instance != this)
        {
            Destroy(gameObject);
            return;
        }
        Instance = this;

        _allViews = new List<MonoBehaviour>
        {
            menuPrincipalView,
            menuPerfilesView,
            preferencesView,
            ingameView
        };
    }

    private void Start()
    {
        NavigateTo(Screen.MenuPrincipal);
    }

    // ?? API pública ??????????????????????????????????????????????????????????

    public void NavigateTo(Screen screen)
    {
        _currentPresenter?.Dispose();
        HideAll();

        _currentPresenter = screen switch
        {
            Screen.MenuPrincipal => Setup(menuPrincipalView, v => new MenuPrincipalPresenter(v, this)),
            Screen.MenuPerfiles => Setup(menuPerfilesView, v => new MenuPerfilesPresenter(v, this)),
            Screen.Preferences => Setup(preferencesView, v => new PreferencesPresenter(v, this)),
            Screen.Ingame => Setup(ingameView, v => new IngamePresenter(v, this)),
            _ => throw new ArgumentOutOfRangeException(nameof(screen))
        };

        _currentPresenter.Initialize();
    }

    // ?? Privados ?????????????????????????????????????????????????????????????

    /// <summary>
    /// Activa la View y construye su Presenter. Siempre el mismo patrón,
    /// sin importar la pantalla.
    /// </summary>
    private PresenterBase Setup<TView>(TView view, Func<TView, PresenterBase> factory)
        where TView : MonoBehaviour
    {
        view.gameObject.SetActive(true);
        return factory(view);
    }

    private void HideAll()
    {
        foreach (var view in _allViews)
            view.gameObject.SetActive(false);
    }
}